"""提示词渲染（规格 §7）。这是全组件唯一由规格逐字钉死文本的地方。

判标题行区的是**模型，不是代码**（规格 §4），所以这里的系统提示词本身就是产品：
术语当场给可判定定义、「没有标题行区」这条路既有规则又有负例、「照抄原文」压住幻觉。

**不给模型的东西**（规格 §7.5，在代码里体现，不在提示词里）：md、本组件的任何推断或候选、
伙伴的其它字段 —— 只给**表范围**与逐行网格。

术语用权威表述：**表范围**、**标题行区**、**数据区**；局部术语只在下面的提示词文本里出现，
且每次出现都同时给出权威表述「标题行区的最下面一行」（规格 §3、§7.1）。
"""
from __future__ import annotations

from itertools import zip_longest

from .input import InputTable

PROMPT_VERSION = "v1"

#: 系统提示词，六块按序（每块开头即所覆盖的规格小节）：
#: 一 术语（§7.1）→ 二 硬约束（§7.2）→ 三「没有标题行区」这条路（§7.3）
#: → 四 四个 few-shot（§7.4）→ 五 输出形状（§6）→ 题头那句「不给的东西」（§7.5）。
SYSTEM_PROMPT = """你在做一件事：看一张表，判定它的**标题行区**，并为每一列给出一条**路径**。

## 一、术语（当场定义，照这些定义判，不要凭字面猜）

- **标题行**：只出现一次、横跨整表宽度、描述整张表的文字（例如 `季度销售报告 2024`；
  合并单元格在每列重复出现，仍算一行）。
  它**不属于标题行区，要排除**，不要拿它的文字当列名。
- **标题行区**：描述各列含义、位于数据之上的**连续行块**（一行或多行）。行号是表内 1-based。
- **列名行**：**标题行区的最下面一行**。`columns` 的取值来自它，`path` 来自标题行区各层。
- **分组表头**：**标题行区的最下面一行之上的那些行**（例如 `2024 年度` 横跨 Q1/Q2）。
  「分组表头」只在本提示词里作局部说明，权威表述是**标题行区的最下面一行之上的行**；
  它们**拼进 `path`**。

## 二、硬约束（逐条照做）

- 只输出 JSON，不要解释、不要 markdown 围栏。
- `columns` 的每一项是「路径」：标题行区各层用 " / " 拼起来，从最上层到标题行区的最下面一行。
- 单层标题行区时，路径就是那个值本身。
- **路径里的每一段必须照抄原文的单元格：不许改写、翻译、补全、纠错、去空格。**
- 空单元格跳过，不拼进路径。
- 如果这张表**没有标题行区**（第一行就是数据），输出
  `{"header_rows": null, "columns": [], "reason": "..."}`。
- **必须给出 `reason`**：一句话说清你凭什么这么判，它是审计线索，不是装饰。

## 三、「没有标题行区」是一条真实存在的答案

- **规则**：如果第一行已经是数据（数字、日期、编码之类），上面没有任何描述各列含义的行，
  那这张表**没有标题行区**，就照实输出 `header_rows: null`、`columns: []`。
- **负例（照这个判）**：
  表范围 A2:C4，三行分别是 `100, 200, 300` / `1, 2, 3` / `0.5, 0.6, 0.7`。
  第一行就是数据，没有标题行区 ⇒ 输出
  `{"header_rows": null, "columns": [], "reason": "第一行就是数据（100/200/300），本表没有标题行区"}`。
- **不要因为「表总该有标题行区」就编一个出来。** 不确定时选 `null`，别猜。

## 四、四个例子（照着模仿）

### 例 1：单层标题行区
- 表范围 A2:C5，行1 是 `产品 | 数量 | 单价`，行2–4 是数据。
- 标题行区只有一行，这一行就是**标题行区的最下面一行**。
- 输出：`{"header_rows": [1, 1], "columns": ["产品", "数量", "单价"], "reason": "行1 是列名行（标题行区的最下面一行），行2 起是数据"}`
  —— 单层标题行区时，路径就是那个值本身。

### 例 2：两层 + 分组表头（横幅重复取值）
- 表范围 A2:D5，行1 是 `2024 年度 | 2024 年度 | 2024 年度 | 2024 年度`，行2 是 `Q1 | Q2 | Q3 | Q4`，行3–4 是数据。
- 行1 是**标题行区的最下面一行之上的那一行**（即分组表头）：横幅 `2024 年度` 在相邻各列上
  **重复取值**，它横跨 Q1–Q4。行2 是**标题行区的最下面一行**。两层都拼进路径，中间用 " / "。
- 输出：`{"header_rows": [1, 2], "columns": ["2024 年度 / Q1", "2024 年度 / Q2", "2024 年度 / Q3", "2024 年度 / Q4"], "reason": "行1 是标题行区的最下面一行之上的那一行（2024 年度 横跨 Q1–Q4，重复取值），行2 是标题行区的最下面一行，行3 起是数据"}`

### 例 3：标题行 + 列名行（标题行要排除，最容易错的一例）
- 表范围 A2:D5，行1 是 `季度销售报告 2024 | 季度销售报告 2024 | 季度销售报告 2024 | 季度销售报告 2024`，行2 是 `产品 | Q1 | Q2 | Q3`，行3–4 是数据。
- 行1 横跨整表宽度、描述整张表 ⇒ 它是**标题行，不属于标题行区，要排除**。
- 行2 是**标题行区的最下面一行**。输出：`{"header_rows": [2, 2], "columns": ["产品", "Q1", "Q2", "Q3"], "reason": "行1 是标题行（横跨整表宽度、描述整张表），排除；行2 是列名行（标题行区的最下面一行）"}`

### 例 4：没有标题行区
- 表范围 A2:C4，行1 是 `100 | 200 | 300`，行2 是 `1 | 2 | 3`，行3 是 `0.5 | 0.6 | 0.7`。
- 第一行就是数据，没有描述各列含义的行 ⇒ 这条路是通的，就照实说。
- 输出：`{"header_rows": null, "columns": [], "reason": "第一行就是数据（100/200/300），本表没有标题行区"}`

## 五、输出形状（只输出这一个 JSON 对象，别的都不要写）

`{"header_rows": [起, 止], "columns": ["路径", "路径"], "reason": "一句话"}`

`header_rows` 是**表内 1-based 的起止行号二元组**；没有标题行区时是 `null`。
用户消息里会按表内行号逐行列出行内容。
"""


def _render_grid(table: InputTable) -> list:
    """按**表内 1-based**行号逐行渲染网格，形如 `行1 | 产品 | 数量 | 单价`。

    `InputTable.columns` 是**每列**内容（列优先），所以先转置成行；单元格照抄原文，不动内容。
    列宽不补齐：整表宽度不保证，但**每格两侧各一个空格**是稳的 —— 弱模型照样读得懂，
    而补齐会把「值本身」和「值加空格」混在一起，反而给了它改字的借口（规格 §7.2 照抄原文）。
    """
    rows = list(zip_longest(*table.columns, fillvalue=""))
    if not rows:
        return ["（本表没有任何行）"]
    return [
        "行{} | {} |".format(index, " | ".join(row))
        for index, row in enumerate(rows, start=1)
    ]


def render_user_message(table: InputTable) -> str:
    """把一张表渲染成用户消息：**表范围** + 逐行网格（行号是**表内 1-based**）。

    只给这两样 —— 不给 md、不给我们的推断或候选、不给伙伴的其它字段（规格 §7.5）。
    """
    lines = [
        "表范围 {}（由上游框定）".format(table.range),
        "下面按表内行号列出；「行1」是本表的第一行",
        "",
    ]
    lines.extend(_render_grid(table))
    return "\n".join(lines)


def build_messages(table: InputTable) -> list[dict]:
    """给客户端的两条消息（Task 5 的 `ask_table` 直接把它交给模型）。"""
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": render_user_message(table)},
    ]
